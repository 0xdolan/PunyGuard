export function blockNameFor(cp: number): string {
  for (const [start, end, name] of UNICODE_BLOCKS) {
    if (cp >= start && cp <= end) return name;
  }
  if (cp > 0xffff) return 'Supplementary Plane';
  return 'Unknown Block';
}
